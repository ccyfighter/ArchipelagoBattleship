# restore-project.ps1
# Convert every *.txt deliverable into its real file name (strip trailing .txt),
# preserving the folder structure, then create Gradle Wrapper scripts.
# Safe to run repeatedly: it only overwrites, it never deletes anything.
param(
    [string]$Root = $PSScriptRoot
)

$ErrorActionPreference = 'Stop'
$Root = (Resolve-Path -LiteralPath $Root).Path
Write-Host "Project root : $Root"

# ---------- 1. strip the .txt suffix ----------
$files = Get-ChildItem -LiteralPath $Root -Recurse -File -Filter '*.txt' -Force |
    Where-Object {
        $rel = $_.FullName.Substring($Root.Length)
        -not ($rel -match '\\(\.git|\.gradle|\.idea|build|Repo)(?:\\)')
    }

$count = 0
foreach ($f in $files) {
    $target = $f.FullName.Substring(0, $f.FullName.Length - 4)
    $dir = Split-Path -Parent $target
    if (-not (Test-Path -LiteralPath $dir)) {
        New-Item -ItemType Directory -Path $dir -Force | Out-Null
    }
    Copy-Item -LiteralPath $f.FullName -Destination $target -Force
    $count++
}
Write-Host "Restored $count files (suffix .txt removed, folder tree kept)."

# ---------- 2. Gradle Wrapper scripts ----------
$wrapperDir = Join-Path $Root 'gradle\wrapper'
if (-not (Test-Path -LiteralPath $wrapperDir)) {
    New-Item -ItemType Directory -Path $wrapperDir -Force | Out-Null
}
$utf8 = New-Object System.Text.UTF8Encoding($false)

$wrapperProps = @'
distributionBase=GRADLE_USER_HOME
distributionPath=wrapper/dists
distributionUrl=https\://services.gradle.org/distributions/gradle-8.7-bin.zip
networkTimeout=10000
validateDistributionUrl=true
zipStoreBase=GRADLE_USER_HOME
zipStorePath=wrapper/dists
'@
[System.IO.File]::WriteAllText(
    (Join-Path $wrapperDir 'gradle-wrapper.properties'),
    ($wrapperProps -replace "`r`n", "`n"),
    $utf8
)

$gradlewSh = @'
#!/bin/sh
APP_HOME=$(cd "$(dirname "$0")" && pwd)
CLASSPATH="$APP_HOME/gradle/wrapper/gradle-wrapper.jar"
if [ -n "$JAVA_HOME" ] ; then
    JAVACMD="$JAVA_HOME/bin/java"
else
    JAVACMD=java
fi
exec "$JAVACMD" -classpath "$CLASSPATH" org.gradle.wrapper.GradleWrapperMain "$@"
'@
[System.IO.File]::WriteAllText(
    (Join-Path $Root 'gradlew'),
    ($gradlewSh -replace "`r`n", "`n"),
    $utf8
)

$gradlewBat = @'
@echo off
setlocal
set APP_HOME=%~dp0
set CLASSPATH=%APP_HOME%gradle\wrapper\gradle-wrapper.jar
if defined JAVA_HOME (set JAVACMD=%JAVA_HOME%\bin\java.exe) else (set JAVACMD=java.exe)
"%JAVACMD%" -classpath "%CLASSPATH%" org.gradle.wrapper.GradleWrapperMain %*
endlocal
'@
[System.IO.File]::WriteAllText((Join-Path $Root 'gradlew.bat'), $gradlewBat, $utf8)

# ---------- 3. try to generate gradle-wrapper.jar locally ----------
$gradle = Get-Command gradle -ErrorAction SilentlyContinue
if ($gradle) {
    $tmp = Join-Path $env:TEMP ('gw_' + [Guid]::NewGuid().ToString('N'))
    New-Item -ItemType Directory -Path $tmp -Force | Out-Null
    Push-Location $tmp
    try {
        & $gradle.Source wrapper --gradle-version 8.7 --distribution-type bin --no-daemon | Out-Null
        Copy-Item -LiteralPath (Join-Path $tmp 'gradlew') -Destination (Join-Path $Root 'gradlew') -Force
        Copy-Item -LiteralPath (Join-Path $tmp 'gradlew.bat') -Destination (Join-Path $Root 'gradlew.bat') -Force
        Copy-Item -LiteralPath (Join-Path $tmp 'gradle\wrapper\gradle-wrapper.jar') -Destination (Join-Path $wrapperDir 'gradle-wrapper.jar') -Force
        Copy-Item -LiteralPath (Join-Path $tmp 'gradle\wrapper\gradle-wrapper.properties') -Destination (Join-Path $wrapperDir 'gradle-wrapper.properties') -Force
        Write-Host "Gradle Wrapper generated locally (jar included)."
    } catch {
        Write-Host "Local Gradle wrapper generation skipped: $_"
    } finally {
        Pop-Location
    }
} else {
    Write-Host "Gradle not installed locally: gradlew / gradlew.bat were written."
    Write-Host "gradle-wrapper.jar is generated by GitHub Actions (Generate Gradle Wrapper step)."
}

Write-Host ""
Write-Host "Done. Now run:  git init ; git add -A ; git commit -m init ; git push -u origin main"
